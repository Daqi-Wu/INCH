function addAfter(file, anchor, text) {
  let s = fs.readFileSync(file, "utf8");
  if (!s.includes(anchor)) { console.log("ANCHOR MISS: " + anchor.slice(0, 40)); process.exit(1); }
  s = s.replace(anchor, anchor + "\n\n" + text);
  fs.writeFileSync(file, s);
}
