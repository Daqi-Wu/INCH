const fs = require("fs");
function patch(file, pairs) {
  let s = fs.readFileSync(file, "utf8");
  for (const [a, b] of pairs) {
    if (!s.includes(a)) { console.log("MISS in " + file + ": " + a.slice(0, 50).replace(/\n/g, " | ")); process.exit(1); }
    s = s.replace(a, b);
  }
  fs.writeFileSync(file, s);
}

